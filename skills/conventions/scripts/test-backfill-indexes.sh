#!/usr/bin/env bash
# test-backfill-indexes.sh — backfill creates missing indexes, skips hand-made
# ones by default, and overwrites them only with --force.
set -uo pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd -P)"
BF="$SCRIPT_DIR/backfill-indexes.sh"

pass=0; fail=0
check() { if eval "$2"; then echo "  ok: $1"; pass=$((pass+1)); else echo "  FAIL: $1"; fail=$((fail+1)); fi; }

TMP="$(mktemp -d)"; trap 'rm -rf "$TMP"' EXIT
ROOT="$TMP/projects"; mkdir -p "$ROOT"

# proj A: plans dir, no index → should be created
mkdir -p "$ROOT/projA/.context/plans"
printf -- '---\ntitle: "P"\nstatus: open\ncreated: 2026-06-01\nupdated: 2026-06-01\n---\n# P\n' \
  > "$ROOT/projA/.context/plans/2026-06-01-p.md"

# proj B: audits dir with a run + inventory, no index → should be created
mkdir -p "$ROOT/projB/.context/audits/20260601-run"
printf -- '---\ntitle: "R"\nstatus: doing\ncreated: 2026-06-01\nmethodology: ux-audit\n---\n# R\n' \
  > "$ROOT/projB/.context/audits/20260601-run/index.md"
printf '| ID | Type | Module | Summary | Status | Severity | Audit Runs | Escalated To | Notes |\n| X-1 | bug | m | s | open | P1 | 2026-06-01 | 2026-06-01 | 20260601-run | — | n |\n' \
  > "$ROOT/projB/.context/audits/00-inventory.md"

# proj C: hand-made plans index (no auto-gen marker) → must be skipped
mkdir -p "$ROOT/projC/.context/plans"
printf -- '---\ntitle: Plans\n---\n# Plans\n\nCurated by hand. Do not lose this.\n' \
  > "$ROOT/projC/.context/plans/00-index.md"

echo "== dry-run --all =="
NO_COLOR=1 bash "$BF" --all "$ROOT" --dry-run >/dev/null 2>&1
check "dry-run wrote nothing for A" '[[ ! -f "$ROOT/projA/.context/plans/00-index.md" ]]'

echo "== real --all (default: skip hand-made) =="
out="$(NO_COLOR=1 bash "$BF" --all "$ROOT" 2>&1)"
check "projA plans index created"   '[[ -f "$ROOT/projA/.context/plans/00-index.md" ]] && grep -q "Auto-generated by" "$ROOT/projA/.context/plans/00-index.md"'
check "projB audits index created"  '[[ -f "$ROOT/projB/.context/audits/00-index.md" ]] && grep -q "1 open / 1 findings" "$ROOT/projB/.context/audits/00-index.md"'
check "projC hand-made preserved"   'grep -q "Curated by hand" "$ROOT/projC/.context/plans/00-index.md"'
check "summary reports a skip"      'printf "%s" "$out" | grep >/dev/null "hand-made skipped"'

echo "== --force overwrites hand-made =="
NO_COLOR=1 bash "$BF" --project "$ROOT/projC" --force >/dev/null 2>&1
check "projC now auto-generated"    'grep -q "Auto-generated by" "$ROOT/projC/.context/plans/00-index.md"'
check "curated content gone"        '! grep -q "Curated by hand" "$ROOT/projC/.context/plans/00-index.md"'

echo "== a failing reindexer does not abort the run (c09) =="
# A copy of the script beside stub reindexers: the plans one fails, the audits one works.
STUB="$TMP/stub"; mkdir -p "$STUB/conventions/scripts" "$STUB/plan/scripts" "$STUB/audit/scripts"
cp "$SCRIPT_DIR/backfill-indexes.sh" "$SCRIPT_DIR/_lib.sh" "$STUB/conventions/scripts/"
printf '#!/usr/bin/env bash\nexit 1\n' > "$STUB/plan/scripts/reindex-plans.sh"
printf '#!/usr/bin/env bash\necho "Auto-generated by stub" > .context/audits/00-index.md\n' > "$STUB/audit/scripts/reindex-audits.sh"
chmod +x "$STUB"/plan/scripts/*.sh "$STUB"/audit/scripts/*.sh
FR="$TMP/failroot"; mkdir -p "$FR/a/.context/plans" "$FR/b/.context/audits"
out="$(NO_COLOR=1 bash "$STUB/conventions/scripts/backfill-indexes.sh" --all "$FR" 2>&1)"; rc=$?
check "failing reindexer: exit 0 as the header promises" '[[ $rc -eq 0 ]]'
check "failing reindexer: the failure is named" 'printf "%s" "$out" | grep -q "reindexer failed"'
check "failing reindexer: later project still processed" '[[ -f "$FR/b/.context/audits/00-index.md" ]]'
check "failing reindexer: summary still prints" 'printf "%s" "$out" | grep -q "hand-made skipped"'
check "failing reindexer: summary counts it" 'printf "%s" "$out" | grep -q "1 failed"'

echo ""
echo "backfill-indexes: $pass passed, $fail failed"
[[ $fail -eq 0 ]]
